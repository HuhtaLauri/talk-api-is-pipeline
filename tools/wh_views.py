"""Generate data/views.sql: DuckDB views over whatever lake folders exist right now.

(DuckDB binds globs at CREATE time, so we only create views for folders with files.)
Re-run with `just wh` or, inside duckdb:  .shell uv run tools/wh_views.py   then   .read data/views.sql
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAKE = ROOT / "data" / "lake"

VIEWS = {
    "v1_customers": "v1/customers/snapshot_*.jsonl",
    "v1_orders": "v1/orders/snapshot_*.jsonl",
    "v2_customers": "v2/customers/batch_*.jsonl",
    "v2_orders": "v2/orders/batch_*.jsonl",
    "v2_customers_ids": "v2/customers_ids/ids_*.jsonl",
    "v3_changes": "v3/changes/batch_*.jsonl",
}

lines = ["-- generated by tools/wh_views.py", ".mode duckbox", ".timer on"]
for view, glob in VIEWS.items():
    if any(LAKE.glob(glob)):
        lines.append(
            f"CREATE OR REPLACE VIEW {view} AS SELECT * FROM read_json_auto("
            f"'{LAKE / glob}', union_by_name = true, filename = true);")
    else:
        lines.append(f"-- {view}: no files yet ({glob})")

if any(LAKE.glob(VIEWS["v3_changes"])):
    lines.append(".read warehouse/models/v3_scd2.sql")

# God view: query the source DB directly. Needs the sqlite extension (`just setup` preinstalls it).
lines.append("ATTACH IF NOT EXISTS 'data/source.db' AS source (TYPE sqlite, READ_ONLY);")
out = ROOT / "data" / "views.sql"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
